#pragma once
// ============================================================================
// sampler.hpp — 采样线程
// ----------------------------------------------------------------------------
// 每个线程独立跑 sample_loop：
//   1. 用 xoshiro256++ 产生两个 53 位均匀数，拼成 106 位均匀数 u
//   2. 由 u 判左右尾（u <= 1/2 → 右尾 x >= 0），对所在尾做上界粗估，
//      上界不到 1σ 的样本直接归入 [0,1)σ 档
//   3. 精算双边坐标 y = -ln(min(u,1-u))，按 SH[k] <= y < SH[k+1] 分档
//      （即 |x| ∈ [k, k+1)σ，±kσ 上下界都参与判定）
//   4. 更新全局最稀有纪录；若 |x| 达到目标 σ 则置 g_stop 停机
// ============================================================================

#include <cstdint>

namespace rs {

// 采样线程入口，seed 为该线程的独立随机种子
void sample_loop(std::uint64_t seed);

} // namespace rs
