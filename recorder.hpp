#pragma once
// ============================================================================
// recorder.hpp — 记录线程
// ----------------------------------------------------------------------------
// 单独线程负责往输出文件写日志：
//   - 启动时写阈值表头
//   - 新纪录产生时立即写一条 [新纪录]
//   - 每 RECORD_INTERVAL_SEC 秒写一条 [每分钟] 快照
//   - 停机时写最终/达标快照
//
// 输出格式示例：
//   [新纪录] 纪录时间: GMT ... | 写入时间: GMT ... | S: ... | x: ... | ...
//     分级统计:
//       环形分布 (x 落在 [k, k+1)σ, 单边):[0,1)σ:202082355 | [1,2)σ:32642538 | ...
//       稀有度 log10 P:                       -0.075 | -0.641 | ...
//
// 注意：x 是单边高斯分位（S = -ln(u) 对应单边尾概率 Phi_bar(x)），
// 因此 [0,1)σ 的理论占比是 Phi(1) ≈ 84.1%（不是双边的 68.3%）。
// ============================================================================

#include <string>

namespace rs {

// 记录线程入口，filename 为追加写入的输出文件
void record_loop(const std::string& filename);

} // namespace rs
