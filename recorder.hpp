// ============================================================================
// recorder.hpp — 记录线程
// ----------------------------------------------------------------------------
// 单独线程负责往输出文件写日志：
//   - 启动时写阈值表头
//   - 新纪录产生时立即写一条 [新纪录]
//   - 每 RECORD_INTERVAL_SEC 秒写一条 [每分钟] 快照
//   - 停机时写最终/达标快照
//
// 输出格式示例：
//   [新纪录] 纪录时间: GMT ... | 写入时间: GMT ... | y: ... | x: ... | ...
//     分级统计:
//       环形分布 (|x| 落在 [k, k+1)σ, 双边):[0,1)σ:202082355 | [1,2)σ:32642538 | ...
//       稀有度 log10 P:                       -0.166 | -0.566 | ...
//
// 注意：分档/纪录/达标全部按**双边** |x| 口径（x = Phi_bar^{-1}(u) ~ N(0,1)
// 是带符号的，左尾 x < 0）。y = -ln(min(u,1-u)) 为双边尾坐标，
// |x| >= kσ ⟺ y >= SH[k]；[0,1)σ 的理论占比是 2(Φ(1)-Φ(0)) = 2Φ(1)-1 ≈ 68.3%。
// ============================================================================

#include <string>

